#!/usr/bin/env python3
"""本次笔记/JSON 回归，在真实 MyGo WebView 中执行，测试目录由 run.sh 隔离。"""
from pathlib import Path
flow = Path(__file__).with_name('flow.py').read_text()
exec(flow[:flow.index('\nshow()\n# --- 计算器')])
exec(flow[flow.index('def ejs('):flow.index('\nedzip=')])
show()
# JSON keys must remain inline and move with the rest of the result.
open_feature('json')
fill('.fx-split textarea', json.dumps({"items": [{"key":i,"nested":{"name":"value"}} for i in range(70)]}))
wait(.5)
check('JSON key 样式与键盘按键隔离', js('(()=>{const k=document.querySelector(".fx-json-key");const s=getComputedStyle(k);return s.position==="static"&&s.display==="inline"&&!k.classList.contains("fx-key")})()'))
check('JSON key 跟随输出滚动', js('(()=>{const p=document.querySelector(".fx-code"),k=p.querySelector(".fx-json-key");const before=k.getBoundingClientRect().top;p.scrollTop=80;return Math.abs((before-k.getBoundingClientRect().top)-80)<2})()'))
shot('json-fixed')
press('Escape')
js('mygo.call("Extensions.Install",%s)' % json.dumps(os.path.join(EXT,'editors-1.1.0.zip')))
os.makedirs(os.path.join(HOME,'notes'),exist_ok=True)
name=os.path.join(HOME,'notes','回归.md')
original='\n\n# 一级标题\n\n正文 **加粗** 结尾\n\n## 二级标题\n\n<style>.demo { color: rgb(220, 30, 40); font-size: 28px; }</style>\n\n<div class="demo">HTML 样式预览</div>\n'
Path(name).write_text(original)
check('打开笔记',open_tool('md','!!document.querySelector(".ProseMirror strong")',15))
eclick('[title="收起文件栏"]'); wait(.25)
check('文件栏可以收起',ejs('getComputedStyle(document.querySelector(".fx-side")).display==="none"'))
check('展开文件栏按钮在编辑区顶栏最左',ejs('document.querySelector(".fx-notes-head > :first-child")?.getAttribute("title")==="展开文件栏"||document.querySelector(".fx-notes-head > :first-child")?.getAttribute("data-tip")==="展开文件栏"'))
eclick('[title="展开文件栏"]'); eclick('[title="大纲"]'); wait(.25)
check('大纲列出两级标题',etexts('.pocket-note-outline .fx-side-list button')==['一级标题','二级标题'])
check('大纲展开时编辑区顶栏不显示大纲按钮',ejs('!document.querySelector(".fx-notes-head [title=大纲],.fx-notes-head [data-tip=大纲]")'))
# Invoke the registered click handler in 整块 mode at the real strong node's position.
eclick_text('.fx-notes-head .ui-seg button','整块'); wait(.25)
check('点击加粗块显示可编辑标记',ejs('(()=>{const v=document.querySelector(".fx-notes-rich").__pm,el=v.dom.querySelector("strong"),e=new MouseEvent("click");Object.defineProperty(e,"target",{value:el});return v.someProp("handleClick",f=>f(v,v.posAtDOM(el,0),e))})()') and ewait_for('!!document.querySelector(".pocket-block-source")'))
check('源码包含星号', '**' in ejs('document.querySelector(".pocket-block-source").value'))
efill('.pocket-block-source','正文 加粗 结尾')
wait(1.2)
check('块编辑实时保存且保留头部空行',Path(name).read_text().startswith('\n\n# ') and '正文 加粗 结尾' in Path(name).read_text(),Path(name).read_text()[:100])
ejs('document.querySelector(".pocket-block-source").dispatchEvent(new KeyboardEvent("keydown",{key:"z",metaKey:true,bubbles:true,cancelable:true}));true');wait(.3)
check('块源码修改可以撤销',ejs('!!document.querySelector(".ProseMirror strong")'))
ejs('(()=>{const v=document.querySelector(".fx-notes-rich").__pm,el=v.dom.querySelector("strong"),e=new MouseEvent("click");Object.defineProperty(e,"target",{value:el});return v.someProp("handleClick",f=>f(v,v.posAtDOM(el,0),e))})()');wait(.2)
efill('.pocket-block-source','正文 加粗 结尾');wait(.2)
ejs('document.querySelector(".pocket-block-source").dispatchEvent(new FocusEvent("blur"));true');wait(.2)
check('去掉标记后没有残留粗体',ejs('!document.querySelector(".ProseMirror strong")'))
eclick('.fx-notes-more > .ui-btn');wait(.15)
eclick_text('.fx-notes-more .fx-menu-item','HTML 沙箱预览');wait(.3)
check('HTML/CSS 在隔离预览中保留',ejs('(()=>{const f=document.querySelector(".pocket-html-preview");return f.getAttribute("sandbox")===""&&f.srcdoc.includes("<style>.demo")&&f.srcdoc.includes("<div class=\\"demo\\">")&&f.srcdoc.includes("default-src")})()'))
shot('notes-html-preview')
eclick('.pocket-note-outline .fx-side-list button');wait(.3)
check('大纲跳转会退出 HTML 预览',ejs('!document.querySelector(".pocket-html-preview")'))
ejs('(()=>{const v=document.querySelector(".fx-notes-rich").__pm;v.dom.dispatchEvent(new KeyboardEvent("keydown",{key:"Enter",ctrlKey:true,shiftKey:true,bubbles:true,cancelable:true}));return true})()');wait(.3)
check('富文本快捷键插入空段落',ejs('(()=>{const v=document.querySelector(".fx-notes-rich").__pm;return v.state.selection.$from.parent.type.name==="paragraph"&&v.state.selection.$from.parent.content.size===0})()'))
eclick('.fx-notes-more > .ui-btn');wait(.15)
eclick_text('.fx-notes-more .fx-menu-item','HTML 沙箱预览');wait(.2)
eclick('.pocket-html-preview-bar button');wait(.2)
eclick_text('.fx-notes-head .ui-seg button','源码');wait(.4)
check('源码模式打开',ewait_for('!!document.querySelector(".fx-notes-body .cm-editor")'))
ejs('document.querySelectorAll(".pocket-note-outline .fx-side-list button")[1].click();true');wait(.2)
check('源码大纲跳转到对应标题',ejs('(()=>{const v=document.querySelector(".fx-notes-body .cm-editor").__cm;return v.state.selection.main.head===v.state.doc.toString().indexOf("## 二级标题")})()'))
cm_type(0,'  hello');wait(.3)
ejs('(()=>{const v=document.querySelector(".fx-notes-body .cm-editor").__cm;v.dispatch({selection:{anchor:4}});v.contentDOM.dispatchEvent(new KeyboardEvent("keydown",{key:"Enter",ctrlKey:true,altKey:true,bubbles:true,cancelable:true}));return true})()');wait(.2)
check('Ctrl+Alt+Enter 上方插行且保留缩进',ejs('document.querySelector(".fx-notes-body .cm-editor").__cm.state.doc.toString()')=='  \n  hello')
eclick('[title="笔记设置"]');wait(.2)
eclick_text('.fx-settings-nav .fx-settings-tab','快捷键');wait(.2)
ejs('document.querySelector("[aria-label=下方插行快捷键]").dispatchEvent(new KeyboardEvent("keydown",{key:"j",ctrlKey:true,altKey:true,bubbles:true,cancelable:true}));true');wait(.3)
check('自定义快捷键生效',ejs('document.querySelector("[aria-label=下方插行快捷键]").value')=='Ctrl+Alt+J')
eclick('.fx-settings-head .ui-btn');wait(.2)
ejs('(()=>{const v=document.querySelector(".fx-notes-body .cm-editor").__cm;v.dispatch({selection:{anchor:v.state.doc.length}});v.contentDOM.dispatchEvent(new KeyboardEvent("keydown",{key:"j",ctrlKey:true,altKey:true,bubbles:true,cancelable:true}));return true})()');wait(.2)
check('自定义下方插行不拆开当前行',ejs('document.querySelector(".fx-notes-body .cm-editor").__cm.state.doc.toString()')=='  \n  hello\n  ')
wait(1)
check('快捷键持久化到宿主',json.loads(Path(HOME,'data/plugins/editors.json').read_text())['notes.prefs']['shortcuts']['below']=='Ctrl+Alt+J')
shot('notes-shortcuts')
header='---\r\ntitle: 保留头部\r\n---\r\n\r\n\r\n'
cm_type(0,header+'# 标题\n\n**原始内容**\n');wait(1)
eclick_text('.fx-notes-head .ui-seg button','实时');wait(.5)
check('frontmatter 笔记重新加载',ewait_for('!!document.querySelector(".ProseMirror strong")'))
ejs('(()=>{const v=document.querySelector(".fx-notes-rich").__pm;v.dispatch(v.state.tr.insertText(" 新内容",v.state.doc.content.size-1));return true})()');wait(1.2)
# CodeMirror normalizes CRLF to LF; compare the exact prefix saved before rich editing.
check('富文本编辑保留 frontmatter 后的多个空行',Path(name).read_text().startswith(header.replace('\r\n','\n')))
check('窄窗口标题仍有可编辑宽度',ejs('document.querySelector(".fx-notes-title").getBoundingClientRect().width>=100'))
shot('notes-final')
print('\nFAILED:',fails)
sys.exit(1 if fails else 0)
