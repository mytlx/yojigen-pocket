#!/usr/bin/env python3
"""Focused native IPv6 peer UI test; run via POCKET_E2E_FLOW=tools/e2e/peer.py."""
from pathlib import Path
source = (Path(__file__).parent / 'flow.py').read_text()
exec(source.split('\nshow()\n# --- 计算器')[0])
exec(source[source.index('def ejs('):source.index('\nedzip=')])
show()
info = js('mygo.call("Extensions.Install",%s)' % json.dumps(os.path.join(EXT, 'peer-1.0.0.zip')))
check('安装口袋直传', info.get('id') == 'peer', info)
open_feature('口袋直传', 1.5)
w = window_by('p=peer')
if not w:
    print(windows()); raise RuntimeError('peer window not found')
win = w['id']
check('扩展界面加载', ewait_for('!!document.querySelector(".peer-identity-card")', 10, win))
shot('peer-idle', win)
js('mygo.call("E2E.PeerFixture")')
check('显示真实 IPv6 连接请求', ewait_for('!!document.querySelector("[aria-label=连接请求]")', 10, win))
eclick_text('button', '同意连接', win)
check('接收方显示三个数字', ewait_for('document.querySelectorAll(".peer-number-options button").length===3', 5, win))
code = js('mygo.call("E2E.PeerCode")')
check('发起方数字匹配其中一项', code in etexts('.peer-number-options button', win))
shot('peer-verification', win)
eclick_text('.peer-number-options button', code, win)
check('数字确认后建立连接', ewait_for('!!document.querySelector(".peer-connected-content")', 5, win))
blocked = js('mygo.call("E2E.PeerTransfer")')
check('发送中阻止退出主程序', blocked is True, blocked)
check('发送校验完成', ewait_for('pocket.call("peer.state").then(s=>s.records.some(r=>r.direction==="send"&&r.status==="completed"))', 15, win))
js('mygo.call("E2E.PeerReceive")')
check('反向接收校验完成', ewait_for('pocket.call("peer.state").then(s=>s.records.some(r=>r.direction==="receive"&&r.status==="completed"))', 15, win))
eclick('.peer-tabs button:nth-child(2)', win); wait(.8)
check('双向传输记录展示', len(etexts('.peer-record', win)) == 2)
shot('peer-history', win)
ejs('document.documentElement.dataset.theme="dark"', win); wait(.3)
shot('peer-dark', win)
check('深色背景跟随主题', ejs('getComputedStyle(document.body).backgroundColor!=="rgb(247, 249, 252)"', win))
eclick_text('button', '断开', win)
check('可正常断开连接', ewait_for('!!document.querySelector(".peer-connect-idle")', 5, win))
print('peer focused failures:', fails)
sys.exit(bool(fails))
